        public static int Count => Points.Length / 2;

        /// <summary>Точка (u, v) внутри силуэта острова (ray-casting по контуру).</summary>
        public static bool Contains(float u, float v)
        {
            bool inside = false;
            int n = Count;
            for (int i = 0, j = n - 1; i < n; j = i++)
            {
                float ui = Points[i * 2], vi = Points[i * 2 + 1];
                float uj = Points[j * 2], vj = Points[j * 2 + 1];
                bool cross = ((vi > v) != (vj > v)) &&
                             (u < (uj - ui) * (v - vi) / (vj - vi) + ui);
                if (cross) inside = !inside;
            }
            return inside;
        }
    }
