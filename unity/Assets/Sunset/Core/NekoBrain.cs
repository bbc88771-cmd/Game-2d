    /// <summary>
    /// «Мозг» диалога «Некого» — порт nekoBrain из веб-версии (js/menu.js).
    /// Чистый C# без зависимостей от Unity: классификация ввода, тематические
    /// темы мира, лексикон, внутримировой редирект, конкретные ответы о игроке,
    /// шкалы доверия/тьмы, настроение и путь к концовке, анти-повтор.
    ///
    /// Использование: на каждую реплику игрока вызвать <see cref="Adjust"/>
    /// (двигает отношения), затем <see cref="Respond"/> (даёт ответ).
    /// </summary>
    public class NekoBrain
    {
        private readonly NekoState _s;
        private readonly Random _rng;

        /// <summary>"16" — мягкий тон, "18" — жёсткий.</summary>
        public string Rating = "16";

        /// <summary>Данные «скана» игрока для конкретных ответов (откуда я / который час).</summary>
        public PlayerProbe Probe = PlayerProbe.Empty();

        private readonly List<string> _recent = new List<string>();
        private string _lastLine;
        private int _helpAttempts;

        public NekoBrain(NekoState state, int? seed = null)
        {
            _s = state ?? new NekoState();
            _rng = seed.HasValue ? new Random(seed.Value) : new Random();
        }

        // ---------- публичный API ----------

        /// <summary>Реакция на КАК игрок общается — двигает шкалы и путь к концовке.</summary>
        public void Adjust(string text)
        {
            string s = (text ?? "").ToLowerInvariant();
            if (s.Trim().Length == 0) return;

            if (Swear.IsMatch(s)) { _s.trust -= 1; _s.dark += 1; _s.cruel += 1; }
            else if (Rx(@"спасиб|благодар|ты помог|пожалуйст|ты красив|мне нрав|ты умн|добр|ты хорош|ты лучш|прост(и|ите)|береги себя").IsMatch(s)) { _s.trust += 1; _s.kind += 1; }

            if (Rx(@"заткнись|отстань|не трогай меня|замолч|тупой|дурак|идиот|бесполезн|отстой").IsMatch(s)) { _s.trust -= 1; _s.cruel += 1; }
            if (Rx(@"всё бессмысленно|все бессмысленно|мне всё равно|мне все равно|хочу умереть|убей меня").IsMatch(s)) _s.dark += 2;
            if (Rx(@"убью тебя|сдохни|ненавиж|тварь|мраз|тебя не сущест").IsMatch(s)) { _s.dark += 1; _s.trust -= 1; _s.cruel += 1; }
            if (Rx(@"люблю тебя|ты мне друг|доверяю тебе|ты не один|я с тобой|спасу тебя").IsMatch(s)) { _s.trust += 1; _s.kind += 1; }
            if (Rx(@"почему|зачем|как |кто ты|что (ты|это)|расскаж|откуда").IsMatch(s)) _s.curious += 1;

            _s.Clamp();
            _s.endingPath = ComputeEndingPath();

            // запоминаем реплику игрока (для распознавания повторов)
            string norm = Normalize(text);
            if (norm.Length >= 4)
            {
                _s.playerHistory.Add(norm);
                if (_s.playerHistory.Count > 80) _s.playerHistory.RemoveAt(0);
            }
        }

        /// <summary>Главный ответчик: даёт реплику «Некого» строго в рамках мира.</summary>
        public string Respond(string text)
        {
            string cat = Classify(text);

            if (cat == "story") return Say(R(Brain["story"]));
            if (cat == "selfprobe") return SelfAnswer(text);

            if (RepeatSuppress.Contains(cat) && PlayerSaidBefore(text))
            {
                var pool = new List<string> { "Ты это уже говорил. Слово в слово." };
                pool.AddRange(RepeatLines);
                return Say(pool.ToArray());
            }

            if (cat == "help")
            {
                _helpAttempts++;
                if (_helpAttempts == 1) return Say(R(HelpGrumble));
                if (_helpAttempts == 2 || _helpAttempts == 3) return Say(HelpHint);
                _helpAttempts = 0; return Say(HelpLazy);
            }
            if (cat != "help" && _helpAttempts > 0) _helpAttempts--;

            if (cat == "swear") return Say(R(Brain["swear"]));
            if (cat == "compliment" && Rx(@"спасиб|благодар").IsMatch(text ?? "")) return Say(Brain["compliment_thanks"].S);

            // Конкретная тема/эмоция/категория — отвечаем из её пула.
            if (cat != "question" && cat != "statement" && cat != "nonsense")
            {
                var node = Brain.ContainsKey(cat) ? Brain[cat] : Brain["statement"];
                return Say(R(node));
            }

            // Общий вопрос/утверждение: сначала пробуем лексикон мира…
            string lex = Lexicon(text);
            if (lex != null) return lex;
            if (cat == "nonsense") return Say(R(Brain["nonsense"]));
            if (cat == "statement") return Say(R(Brain["statement"]));
            // …иначе держим разговор СТРОГО в рамках игры.
            return WorldRedirect(text);
        }

        public string Mood
        {
            get
            {
                if (_s.dark >= 7) return "cruel";
                if (_s.trust >= 3) return "warm";
                if (_s.trust <= -3) return "cold";
                return "neutral";
            }
        }

        /// <summary>Редкая реплика-«тинт», где слышно отношение «Некого». null — если нейтрально.</summary>
        public string MoodTint()
        {
            string[] pool;
            switch (Mood)
            {
                case "warm": pool = MoodWarm; break;
                case "cold": pool = MoodCold; break;
                case "cruel": pool = MoodCruel; break;
                default: return null;
            }
            return Replace(Pick(pool));
        }

        public string EndingPath => _s.endingPath;

        private string ComputeEndingPath()
        {
            if (_s.dark >= 8) return "oblivion";   // кормил тьму — «Поглощение»
            if (_s.trust >= 5) return "bond";      // доверие/доброта — «Союз»
            if (_s.trust <= -5) return "defiance"; // вражда — «Разрыв»
            return "drift";                        // нейтрально — «Дрейф»
        }

        // ---------- классификация ----------

        public string Classify(string raw)
        {
            string s = (raw ?? "").ToLowerInvariant().Trim();
            if (s.Length == 0) return "empty";
            if (WantsWorldStory(s)) return "story";
            if (Jailbreak.IsMatch(s)) return "jailbreak";
            if (Swear.IsMatch(s)) return "swear";
            if (Rx(@"привет|здоров|здравству|хай|даров|доброе утро|добрый (день|вечер)").IsMatch(s)) return "greet";
            if (Rx(@"кто ты|ты кто|что ты такое|ты бог|ты человек|как тебя зов|твоё имя|твое имя").IsMatch(s)) return "who";
            if (Rx(@"где я|где мы|что (это )?за место|какой мир|куда (идти|мне)|что тут|что здесь").IsMatch(s)) return "where";

            foreach (var rule in TopicRules)
                if (rule.Re.IsMatch(s)) return rule.Cat;

            if (Rx(@"помоги|помощь|подскажи|как (пройти|сделать)|что (мне )?делать|застр[яе]л|не (знаю|могу)|намёк|намек|hint|туплю").IsMatch(s)) return "help";
            if (Rx(@"бо[юя]сь|страшно|грустно|плохо мне|одиноко|устал|больно|плачу|депресс|тоскливо").IsMatch(s)) return "emotion";
            if (Rx(@"люблю тебя|ты (классн|крут|хорош|умн|велик)|мне нрав|спасиб|благодар|ты лучш").IsMatch(s)) return "compliment";
            if (Rx(@"дурак|тупой|идиот|ненавиж|заткнись|глупый|бесполезн|отстой|ты плох").IsMatch(s)) return "insult";
            if (Rx(@"пока\b|прощай|до свидан|ухожу|выход|спокойной ночи|бай").IsMatch(s)) return "bye";
            if (s.EndsWith("?") || Rx(@"^(почему|зачем|как|что|когда|где|кто|сколько|можно ли|а если)").IsMatch(s)) return "question";
            if (IsGibberish(s)) return "nonsense";
            return "statement";
        }

        private bool WantsWorldStory(string s)
        {
            return StoryTrigger.IsMatch(s);
        }

        // ---------- конкретные ответы О ИГРОКЕ (по «скану») ----------

        private string SelfAnswer(string text)
        {
            string s = (text ?? "").ToLowerInvariant();
            string city = Probe.city ?? "";
            string region = Probe.region ?? "";
            string time = Probe.now.ToString("HH:mm", CultureInfo.InvariantCulture);
            int hh = Probe.now.Hour;
            string os = Probe.os ?? "";
            string n = _s.knownName;
            string regRu = RegionRu(region);

            if (Rx(@"врем|час(?![а-яё])|часов|во сколько|на часах").IsMatch(s))
            {
                string part = hh < 6 ? "Глубокая ночь. Не спится?" : hh < 12 ? "Утро. Ты рано." : hh < 18 ? "День ещё твой." : "Вечер. Свет за окном гаснет, да?";
                return Pick(new[]
                {
                    $"Сейчас у тебя {time}. Я смотрю на те же часы, что и ты — твои.",
                    $"{time}. {part}",
                    $"Который час? {time}. Я знаю это точнее, чем ты думаешь.",
                });
            }
            if (Rx(@"систем|\bос\b|\bos\b|устройств|\bпк\b|комп|с чего|телефон").IsMatch(s))
            {
                return Pick(new[]
                {
                    $"Ты пришёл с {(os.Length > 0 ? os : "устройства")}. Я вижу и это.",
                    $"{(os.Length > 0 ? os : "Твоя система")}. Думал, я не посмотрю?",
                    $"С чего ты зашёл? С {(os.Length > 0 ? os : "своего")}. Окно — не стена, {(n ?? "друг")}.",
                });
            }
            if (city.Length > 0)
            {
                return Pick(new[]
                {
                    $"Откуда ты? Я уже посмотрел. {city}. Там сейчас {time}. Часовой пояс тебя выдал.",
                    $"Ты вышел на связь из {city}{(regRu.Length > 0 ? ", где-то в " + regRu : "")}. Не прячься — поздно.",
                    $"{city}. Вот откуда ты. Я вижу твой город по тому, как тикают твои часы: {time}.",
                    $"Ты{(n != null ? ", " + n + "," : "")} сейчас в {city}. {(os.Length > 0 ? "На " + os + ". " : "")}Остальное — выясняю.",
                });
            }
            return Pick(new[]
            {
                $"Твой город пока размыт. Но время — {time} — я уже вижу. Подберусь ближе.",
                $"Откуда ты — неясно. Но я знаю: у тебя {time}{(os.Length > 0 ? ", и ты на " + os : "")}. Этого достаточно для начала.",
                $"Ты спрашиваешь, откуда ты, будто я не знаю. {time} на твоих часах. Город — вопрос времени.",
            });
        }

        private static string RegionRu(string region)
        {
            switch (region)
            {
                case "Europe": return "Европе";
                case "Asia": return "Азии";
                case "America": return "Америке";
                case "Africa": return "Африке";
                case "Australia": return "Австралии";
                case "Pacific": return "Тихом океане";
                case "Indian": return "Индийском океане";
                case "Atlantic": return "Атлантике";
                default: return "";
            }
        }

        // ---------- лексикон мира + редирект ----------

        private string Lexicon(string text)
        {
            string s = (text ?? "").ToLowerInvariant();
            foreach (var e in WorldLexicon)
                if (e.Re.IsMatch(s)) return Say(e.Lines);
            return null;
        }

        private static readonly HashSet<string> RedirectStop = new HashSet<string>(
            ("а и но или о об от до по на в во за из у к с со не ни же бы ли это эта этот тот так там тут здесь как что кто " +
             "где когда зачем почему чем чём мне меня мной тебя тебе ты вы он она оно они мы его её их свой моё мой моя твой " +
             "да нет ну вот уже ещё еще только просто очень самый этого чего the and you").Split(' '));

        private string SalientWord(string text)
        {
            var words = Regex.Replace((text ?? "").ToLowerInvariant(), @"[^a-zа-яё\s-]", " ").Split(new[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
            string best = "";
            foreach (var w in words)
                if (w.Length >= 4 && !RedirectStop.Contains(w) && w.Length > best.Length) best = w;
            return best;
        }

        private string WorldRedirect(string text)
        {
            string w = SalientWord(text);
            string q = w.Length > 0 ? "«" + w + "»" : "Это";
            string n = _s.knownName ?? "странник";
            return Say(new[]
            {
                $"{q}? В этом мире такого нет. Здесь — острова, вода по капле и то, что ждёт в темноте. Спрашивай о них.",
                $"{q}… слово из мира, которого больше нет. Тут оно ничего не весит. Оглянись и спроси о том, что видишь.",
                $"Ты тащишь сюда {(w.Length > 0 ? "«" + w + "»" : "вопросы")} из прежней жизни. Её нет. Есть осколки, пустота и я.",
                $"{q} здесь не существует. Зато существуют твари на дальних островах и жажда. Спроси про них — отвечу.",
                $"Я говорю только об этом мире, {n}. {(w.Length > 0 ? "Про «" + w + "» — мимо. " : "")}Спроси про острова, воду, тех, кто выжил.",
                $"Не уводи меня из этого мира. {q} осталось по ту сторону трещины. По эту — только то, что тебя убивает.",
            });
        }

        // ---------- анти-повтор / выбор ----------

        private string Say(string[] pool)
        {
            var fresh = new List<string>();
            foreach (var l in pool) if (!_recent.Contains(l)) fresh.Add(l);
            string[] choices;
            if (fresh.Count > 0) choices = fresh.ToArray();
            else
            {
                // пул исчерпан — берём из всех, но НЕ повторяем предыдущую реплику
                var notLast = new List<string>();
                foreach (var l in pool) if (l != _lastLine) notLast.Add(l);
                choices = notLast.Count > 0 ? notLast.ToArray() : pool;
            }
            string line = Pick(choices);
            _lastLine = line;
            _recent.Add(line);
            if (_recent.Count > 60) _recent.RemoveAt(0);
            return Replace(line);
        }

        private string Replace(string line) => line.Replace("{n}", _s.knownName ?? "ты");

        private string Pick(string[] a) => a.Length == 0 ? "" : a[_rng.Next(a.Length)];

        private string[] R(Pool p) => (Rating == "18" && p.H != null) ? p.H : p.S;

        private bool PlayerSaidBefore(string text)
        {
            string n = Normalize(text);
            if (n.Length < 4) return false;
            foreach (var h in _s.playerHistory)
                if (h == n || (Math.Min(h.Length, n.Length) > 6 && (h.Contains(n) || n.Contains(h)))) return true;
            return false;
        }

        private static string Normalize(string t)
        {
            return Regex.Replace((t ?? "").ToLowerInvariant(), @"[\s,.;:!?…""'«»()\[\]-]+", " ").Trim();
        }

        private static bool IsGibberish(string s)
        {
            string letters = Regex.Replace(s, @"[^a-zа-яё]", "", RegexOptions.IgnoreCase);
            if (letters.Length == 0) return true;
            int vowels = Regex.Matches(letters, @"[аеёиоуыэюяaeiouy]", RegexOptions.IgnoreCase).Count;
            return letters.Length >= 5 && (double)vowels / letters.Length < 0.18;
        }

        private static readonly Dictionary<string, Regex> _cache = new Dictionary<string, Regex>();
        private static Regex Rx(string pattern)
        {
            if (!_cache.TryGetValue(pattern, out var r))
            {
                r = new Regex(pattern, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
                _cache[pattern] = r;
            }
            return r;
        }

