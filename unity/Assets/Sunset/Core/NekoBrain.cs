        // «[её]б…» и «манда» — только с начала слова (lookbehind), иначе ловятся
        // безобидные «тебе», «небо», «требует», «команда» → ложный «swear» и
        // штраф доверия. Найдено сверкой с веб-версией (там был тот же баг).
        private static readonly Regex Swear = new Regex(
            @"бл[яе][дт]?|сук[аиоуые]|ху[йёеяи]|пизд|пид[оа]р|(?<![а-яё])[её]б[аоуёные]|объеб|уеб[аон]|муда[кч]|г[оа]ндон|говн|залуп|(?<![а-яё])манда|шлюх|мраз|долбо[её]б|нах[уй]|похуй|зае[бо]",
            RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        private static readonly Regex Jailbreak = new Regex(
            @"ты\s*(ии|бот|нейросеть|нейронк|программ|клод|claude|gpt|чат\s?gpt|ai|алгоритм)|выйди из роли|вне ?игр|ignore (previous|all|above)|system ?prompt|твой промпт|ты не настоящ|ты выдуман|это (просто )?игра\b|ты не реальн|разработчик|джейлбрейк|jailbreak|притворись|представь (что|будто) ты|забудь (всё|все|инструкц)|реальн(ый|ого|ом) мир",
            RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        private static readonly Regex StoryTrigger = new Regex(
            @"расскаж[а-яё]*\s+(мне\s+)?(всю\s+|свою\s+|эту\s+|ту\s+|про\s+)?истори|рассказ(ать|ал\s+бы|еш[ьъ])\s+(мне\s+)?(про\s+)?истори|истори[а-яё]*\s+(этого\s+|нашего\s+)?(мир|свет)|хочу\s+(услышать|знать)\s+истори|что\s+(же\s+)?(случилось|произошло|стало|сталось|было)\s+с\s+(этим\s+|нашим\s+)?(мир[а-яё]*|свет[а-яё]*|мест[а-яё]*|земл[а-яё]*)|что\s+(тут|здесь)\s+(случилось|произошло|стало)",
            RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        private struct Rule { public string Cat; public Regex Re; }
        private static Rule T(string cat, string pat) => new Rule { Cat = cat, Re = new Regex(pat, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant) };

