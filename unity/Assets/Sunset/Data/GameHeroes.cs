    /// <summary>Способность героя: название и описание (на клавише).</summary>
    [Serializable]
    public class HeroSkill
    {
        public string name;
        public string desc;
        public HeroSkill(string name, string desc) { this.name = name; this.desc = desc; }
    }

    /// <summary>
    /// Полное описание героя (порт HEROES + HERO_DETAIL + HERO_SECRET из веб-версии):
    /// роль, 4 способности на клавишах, секретная 5-я, плюсы/минусы, предыстория и
    /// как герой попал на остров.
    /// </summary>
    [Serializable]
    public class HeroDef
    {
        public string id;
        public string name;
        public string tagline;   // короткая строка для меню
        public string role;      // роль на экране героя
        public HeroSkill[] skills;       // 4 способности
        public HeroSkill secret;         // секретная 5-я
        public string[] pros;
        public string[] cons;
        public string story;
        public string arrival;
        public string portrait;  // имя спрайта в Resources/Sunset (hero_<id>)

        public HeroDef(string id, string name, string tagline, string role,
            HeroSkill[] skills, HeroSkill secret, string[] pros, string[] cons,
            string story, string arrival)
        {
            this.id = id; this.name = name; this.tagline = tagline; this.role = role;
            this.skills = skills; this.secret = secret; this.pros = pros; this.cons = cons;
            this.story = story; this.arrival = arrival; this.portrait = "hero_" + id;
        }
    }

