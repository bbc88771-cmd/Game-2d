    /// Один нарративный слайд вступительной катсцены (порт массива SLIDES из
    /// веб-версии): фон, вариант Ken Burns, частота «колокола» и текстовые биты.
    /// </summary>
    [Serializable]
    public class CutsceneSlide
    {
        /// <summary>Имя спрайта в Resources/Sunset (без расширения). null — чёрный космос.</summary>
        public string image;

        /// <summary>Вариант Ken Burns: false — наезд (kb), true — отъезд (kb2).</summary>
        public bool kenBurnsOut;

        /// <summary>Частота «колокола» на смене кадра (Гц) — для аудио-порта.</summary>
        public float bellFreq;

        /// <summary>Слайд озвучен «Неким» — подпись красная (голос Некого).</summary>
        public bool neko;

        /// <summary>Текстовые биты (предложения), показываются поочерёдно.</summary>
        public string[] beats;

        public CutsceneSlide(string image, bool kenBurnsOut, float bellFreq, bool neko, string[] beats)
        {
            this.image = image; this.kenBurnsOut = kenBurnsOut; this.bellFreq = bellFreq;
            this.neko = neko; this.beats = beats;
        }

        /// <summary>Суммарное число символов во всех битах (для распределения длительностей).</summary>
        public int CharCount
        {
            get
            {
                int n = 0;
                if (beats != null)
                    foreach (var b in beats) n += b?.Length ?? 0;
                return n;
            }
        }
    }

