        public static int Count => Slides.Length;

        /// <summary>Суммарное число символов во всех слайдах.</summary>
        public static int TotalCharCount
        {
            get
            {
                int n = 0;
                foreach (var s in Slides) n += s.CharCount;
                return n;
            }
        }

        /// <summary>
        /// Длительности слайдов (мс), распределённые пропорционально числу символов
        /// в пределах общей длительности <paramref name="totalDurationMs"/>. Каждый
        /// слайд — минимум 8000 мс (как в веб-версии).
        /// </summary>
        public static int[] SlideDurationsMs(double totalDurationMs)
        {
            int total = TotalCharCount;
            var result = new int[Slides.Length];
            for (int i = 0; i < Slides.Length; i++)
            {
                double share = total > 0 ? (double)Slides[i].CharCount / total : 1.0 / Slides.Length;
                result[i] = Math.Max(8000, (int)Math.Round(share * totalDurationMs));
            }
            return result;
        }
